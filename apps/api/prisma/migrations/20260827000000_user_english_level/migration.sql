-- P4：学生当前英语难度的单一事实来源。
--
-- 纯新增一列，可空、无默认值、**不回填**。
--
-- 为什么不回填：回填只能靠猜（「最近一次答卷所在场次的层」），而学生
-- 换过层、代答过、或那天他那层没开时都会猜错；猜错的后果是他明天被
-- 锁进错的难度，还得找老师改。null 有明确且安全的兼容路径 —— 沿用
-- 旧行为（扫码时现选），首次扫码成功后由服务端条件写入落定。让 35 个
-- 人各自选一次，比错锁其中几个便宜。
--
-- 回滚：ALTER TABLE "User" DROP COLUMN "englishLevel";
-- 该列不含任何原有数据，删除不影响历史答卷 / 成绩 / 场次。
ALTER TABLE "User" ADD COLUMN "englishLevel" "EnglishLevel";
