import { describe, expect, it } from 'vitest';
import { streakFromDays } from './vocab-review.service';

/**
 * 连胜的「上学日」口径（2026-08-24 学生十问修复 #3）。
 *
 * 背景：生产日志显示复习只发生在周二到周五，周末为零 —— 严格连续
 * 日历日的旧规则下，连胜上限是 4，且每周一早上必显示 0（上次复习是
 * 周五，不是「今天或昨天」）。周五认真复习的学生周一被清零。
 *
 * 2026-08 的日历锚点：2026-08-21 是周五，2026-08-24 是周一。
 */
describe('streakFromDays — 上学日连胜', () => {
  it('空记录 → 0', () => {
    expect(streakFromDays([], '2026-08-24')).toBe(0);
  });

  it('只有今天 → 1', () => {
    expect(streakFromDays(['2026-08-24'], '2026-08-24')).toBe(1);
  });

  it('周五复习过、今天周一 → 连胜活着（旧规则会清零）', () => {
    expect(streakFromDays(['2026-08-21'], '2026-08-24')).toBe(1);
  });

  it('周二到周五连续四天、今天周一 → 4，不因周末断', () => {
    expect(
      streakFromDays(['2026-08-21', '2026-08-20', '2026-08-19', '2026-08-18'], '2026-08-24'),
    ).toBe(4);
  });

  it('跨周末续上：上周五 + 本周一都复习 → 2', () => {
    expect(streakFromDays(['2026-08-24', '2026-08-21'], '2026-08-24')).toBe(2);
  });

  it('周六在家复习也计入链条：五、六、下周一 → 3', () => {
    expect(streakFromDays(['2026-08-24', '2026-08-22', '2026-08-21'], '2026-08-24')).toBe(3);
  });

  it('空着的工作日会断（冻结关掉时）：上次是周四、今天周一 → 0', () => {
    expect(streakFromDays(['2026-08-20'], '2026-08-24', 0)).toBe(0);
  });

  it('链条中段空一个工作日（冻结关掉时）→ 从断点截断：周一+上周五+上周三 → 2', () => {
    // 8/19（上周三）与 8/21（上周五）之间隔着 8/20 周四没复习 → 断
    expect(streakFromDays(['2026-08-24', '2026-08-21', '2026-08-19'], '2026-08-24', 0)).toBe(2);
  });

  // ── 自动冻结（默认额度 2）──

  it('冻结：单日缺口自动补上 —— 病一天回来连胜还在', () => {
    // 周四复习、周五病假、今天周一 → 豁免周五
    expect(streakFromDays(['2026-08-20'], '2026-08-24')).toBe(1);
    // 链条中段空一个周四 → 豁免后三天连上
    expect(streakFromDays(['2026-08-24', '2026-08-21', '2026-08-19'], '2026-08-24')).toBe(3);
  });

  it('冻结额度只有 2：第三个单日缺口照断', () => {
    // 8/24(一) ← 空8/21(五) ← 8/20(四) ← 空8/19(三) ← 8/18(二) ← 空8/17(一) ← 8/14(五)
    // 前两个缺口吃掉额度，第三个断 → 连胜 = 3（24、20、18）
    expect(streakFromDays(['2026-08-24', '2026-08-20', '2026-08-18', '2026-08-14'], '2026-08-24')).toBe(3);
  });

  it('冻结不救真实中断：空两个工作日的缺口照断', () => {
    // 上次 8/19（周三），今天 8/24（周一）→ 空了周四+周五两个工作日
    expect(streakFromDays(['2026-08-19'], '2026-08-24')).toBe(0);
  });

  it('今天还没复习、昨天（工作日）复习过 → 不清零', () => {
    // 8/25 是周二，8/24 周一复习过
    expect(streakFromDays(['2026-08-24'], '2026-08-25')).toBe(1);
  });

  it('隔了整整一周没复习 → 0', () => {
    expect(streakFromDays(['2026-08-14'], '2026-08-24')).toBe(0);
  });
});
